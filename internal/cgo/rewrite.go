// The C side of the runtime (runtime/core/src/cgo.c).
const cPrologue = `/* marmot: C calls are bracketed by the runtime (internal/cgo). */
extern void rt_cgo_enter(void);
extern void rt_cgo_exit(void);
extern void rt_cgo_enter_fast(void);
extern void rt_cgo_exit_fast(void);
extern void rt_cgo_exit_errno(int);
`

// helpers are the C.xxx functions written in Go.
var helpers = map[string]string{
	"CString": `	n := len(p0)
	p := _cgo_cmalloc(uintptr(n + 1))
	b := unsafe.Slice((*byte)(p), n+1)
	copy(b, p0)
	b[n] = 0
	return (%s)(p)`,
	"CBytes": `	p := _cgo_cmalloc(uintptr(len(p0)))
	copy(unsafe.Slice((*byte)(p), len(p0)), p0)
	return p`,
	"GoString": `	if p0 == nil {
		return ""
	}
	p := unsafe.Pointer(p0)
	return string(unsafe.Slice((*byte)(p), _cgo_strlen(p)))`,
	"GoStringN": `	if p1 <= 0 {
		return ""
	}
	return string(unsafe.Slice((*byte)(unsafe.Pointer(p0)), int(p1)))`,
	"GoBytes": `	if p1 <= 0 {
		return []byte{}
	}
	b := make([]byte, int(p1))
	copy(b, unsafe.Slice((*byte)(p0), int(p1)))
	return b`,
	"_CMalloc": `	return _cgo_cmalloc(uintptr(p0))`,
}

const helperDecls = `
//go:linkname _cgo_libc_malloc malloc
func _cgo_libc_malloc(n uintptr) unsafe.Pointer

//go:linkname _cgo_strlen strlen
func _cgo_strlen(p unsafe.Pointer) int

//go:linkname _cgo_keep rt_cgo_keep
func _cgo_keep(p unsafe.Pointer)

//go:linkname _cgo_rt_errno rt_cgo_errno
func _cgo_rt_errno() int32

func _cgo_cmalloc(n uintptr) unsafe.Pointer {
	p := _cgo_libc_malloc(n)
	if p == nil && n == 0 {
		p = _cgo_libc_malloc(1)
	}
	if p == nil {
		panic("runtime: C malloc failed")
	}
	return p
}

func _cgo_b2u(b bool) uint32 {
	if b {
		return 1
	}
	return 0
}

// _cgo_Incomplete stands for runtime/cgo.Incomplete (C types without a
// definition).
type _cgo_Incomplete struct{ _ [0]func() }
`

var reWrapper = regexp.MustCompile(`^_cgo_([0-9a-f]+)_(Cfunc|C2func)_(\w+)$`)

// cProto is a C wrapper's prototype, as cgo writes it.
type cProto struct {
	file   string   // the .cgo2.c file
	ret    string   // result type
	params []string // "TYPE pN"
}

// rewrite rewrites the cgo output in dir.
func rewrite(dir string, bp *build.Package, mk marks) error {
	protos, err := readProtos(dir)
	if err != nil {
		return err
	}
	path := filepath.Join(dir, "_cgo_gotypes.go")
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	types := map[string]ast.Expr{}
	for _, d := range f.Decls {
		if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.TYPE {
			for _, s := range g.Specs {
				ts := s.(*ast.TypeSpec)
				types[ts.Name.Name] = ts.Type
			}
		}
	}
	src := func(n ast.Node) string {
		var b bytes.Buffer
		format.Node(&b, fset, n)
		return b.String()
	}
	externs := map[string]*ast.FuncDecl{}
	for _, d := range f.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Body == nil && fd.Doc != nil {
			for _, c := range fd.Doc.List {
				if strings.HasPrefix(c.Text, "//extern ") {
					externs[fd.Name.Name] = fd
				}
			}
		}
	}
	cAdd := map[string]*strings.Builder{} // C to append, by .cgo2.c file
	addC := func(file, text string) {
		if cAdd[file] == nil {
			cAdd[file] = &strings.Builder{}
		}
		cAdd[file].WriteString(text)
	}

	var exports []*ast.FuncDecl
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by cmd/cgo and marmot; DO NOT EDIT.\n\npackage %s\n\n", f.Name.Name)
	hash := ""
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.GenDecl:
			switch d.Tok {
			case token.IMPORT:
				for _, s := range d.Specs {
					is := s.(*ast.ImportSpec)
					if is.Path.Value == `"runtime/cgo"` {
						continue
					}
					out.WriteString("import " + src(is) + "\n")
				}
				continue
			case token.TYPE:
				if len(d.Specs) == 1 && d.Specs[0].(*ast.TypeSpec).Name.Name == "_" {
					continue // type _ _cgopackage.Incomplete
				}
			case token.VAR:
				if v := cvar(d); v != nil {
					name := v.Names[0].Name
					c := strings.TrimPrefix(name, "Cvar_")
					getter := fmt.Sprintf("_cgo_%s_Cvar_%s", hashOf(externs), c)
					fmt.Fprintf(&out, "\n//go:linkname %s %s\nfunc %s() unsafe.Pointer\n\nvar %s = (%s)(%s())\n",
						getter, getter, getter, name, src(v.Type), getter)
					file := cgo2For(dir, bp, name)
					addC(file, fmt.Sprintf("\nvoid *%s(void) { return (void *)&%s; }\n", getter, c))
					continue
				}
			}
			d.Doc = nil
			out.WriteString(src(d) + "\n\n")
		case *ast.FuncDecl:
			name := d.Name.Name
			switch {
			case name == "_Cgo_no_callback" && d.Body == nil:
				out.WriteString("func _Cgo_no_callback(bool) {}\n\n")
				continue
			case (name == "_cgoCheckPointer" || name == "_cgoCheckResult") && d.Body == nil:
				d.Doc = nil
				d.Body = &ast.BlockStmt{}
				out.WriteString(src(d) + "\n\n")
				continue
			case externs[name] != nil:
				continue // written with its _Cfunc_ function
			}
			if strings.HasPrefix(name, "Cgoexp_") && d.Body != nil {
				exports = append(exports, d)
				continue
			}
			m := reCfunc.FindStringSubmatch(name)
			if m == nil || d.Body == nil {
				d.Doc = nil
				out.WriteString(src(d) + "\n\n")
				continue
			}
			kind, cname := m[1], m[2]
			var w string
			for e := range externs {
				if wm := reWrapper.FindStringSubmatch(e); wm != nil && wm[2] == kind && wm[3] == cname {
					w, hash = e, wm[1]
				}
			}
			if w == "" {
				return fmt.Errorf("no C wrapper for %s", name)
			}
			ext := externs[w]
			sig := sigText(src, d.Type)
			if body, ok := helpers[cname]; ok && kind == "Cfunc" {
				if strings.Contains(body, "%s") {
					body = fmt.Sprintf(body, src(d.Type.Results.List[0].Type))
				}
				fmt.Fprintf(&out, "func %s%s {\n%s\n}\n\n", name, sig, body)
				continue
			}
			text, ctext, err := callC(w, cname, kind, ext, d, protos[w], types, src)
			if err != nil {
				return fmt.Errorf("%s: %v", name, err)
			}
			out.WriteString(text)
			if ctext != "" {
				addC(protos[w].file, ctext)
			}
		}
	}
	if hash == "" {
		hash = hashOf(externs)
	}
	var expC map[string]string
	if len(exports) > 0 {
		var err error
		if expC, err = exportsGo(&out, exports, hash, types, src); err != nil {
			return err
		}
	}
	out.WriteString(helperDecls)
	text := strings.ReplaceAll(out.String(), "_cgopackage.Incomplete", "_cgo_Incomplete")
	formatted, err := format.Source([]byte(text))
	if err != nil {
		os.WriteFile(path+".bad", []byte(text), 0o644)
		return fmt.Errorf("generated Go: %v", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return err
	}
	// The C side: bracket each wrapper, add the adapters and getters.
	files, _ := filepath.Glob(filepath.Join(dir, "*.cgo2.c"))
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		c := bracket(string(data), mk)
		if b := cAdd[file]; b != nil {
			c += b.String()
		}
		if err := os.WriteFile(file, []byte(cPrologue+c), 0o644); err != nil {
			return err
		}
	}
	if exp := filepath.Join(dir, "_cgo_export.c"); fileExists(exp) {
		if len(exports) == 0 {
			os.Remove(exp)
		} else if err := exportsC(exp, expC); err != nil {
			return err
		}
	}
	return nil
}

// An exported Go function NAME is called from C through cgo's C function
// NAME in _cgo_export.c, which calls the Go function _cgoexp_HASH_NAME
// (a C-level symbol, so whole program dead code removal keeps it) with
// the runtime's callback entry and exit around the call. Aggregates go by
// pointer and small integers as 32-bit values, as for calls into C.

// exportsGo writes the Go side of the exports and returns, by export
// name, the C declaration and call of its Go function.
func exportsGo(out *strings.Builder, exports []*ast.FuncDecl, hash string, types map[string]ast.Expr,
	src func(ast.Node) string) (map[string]string, error) {
	cside := map[string]string{}
	for _, d := range exports {
		name := strings.TrimPrefix(d.Name.Name, "Cgoexp_")
		sym := fmt.Sprintf("_cgoexp_%s_%s", hash, name)
		var params []ast.Expr
		for _, f := range d.Type.Params.List {
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			for i := 0; i < n; i++ {
				params = append(params, f.Type)
			}
		}
		var results []ast.Expr
		if d.Type.Results != nil {
			for _, f := range d.Type.Results.List {
				n := len(f.Names)
				if n == 0 {
					n = 1
				}
				for i := 0; i < n; i++ {
					results = append(results, f.Type)
				}
			}
		}
		var gps, args, cps, cargs []string
		for i, t := range params {
			pn := fmt.Sprintf("p%d", i)
			switch {
			case aggregate(t, types):
				gps = append(gps, pn+" *"+src(t))
				args = append(args, "*"+pn)
				cps = append(cps, "ptr")
				cargs = append(cargs, "&"+pn)
			case widen(t, types) != "":
				w := widen(t, types)
				gps = append(gps, pn+" "+w)
				if isBool(t, types) {
					args = append(args, pn+" != 0")
				} else {
					args = append(args, src(t)+"("+pn+")")
				}
				cps = append(cps, w+"_t")
				cargs = append(cargs, pn)
			default:
				gps = append(gps, pn+" "+src(t))
				args = append(args, pn)
				cps = append(cps, "same")
				cargs = append(cargs, pn)
			}
		}
		call := strings.TrimPrefix(d.Name.Name, "Cgoexp_") + "(" + strings.Join(args, ", ") + ")"
		var body, ret, cret string
		switch {
		case len(results) == 0:
			body = "\t" + call + "\n"
			cret = "void"
		case len(results) == 1 && aggregate(results[0], types):
			gps = append(gps, "r *"+src(results[0]))
			body = "\t*r = " + call + "\n"
			cret = "ptr"
		case len(results) == 1 && widen(results[0], types) != "":
			w := widen(results[0], types)
			ret = " " + w
			if isBool(results[0], types) {
				body = "\treturn _cgo_b2u(" + call + ")\n"
			} else {
				body = "\treturn " + w + "(" + call + ")\n"
			}
			cret = w + "_t"
		case len(results) == 1:
			ret = " " + src(results[0])
			body = "\treturn " + call + "\n"
			cret = "same"
		default:
			// Several results: C gets a struct of them.
			var fields, lhs []string
			for i, t := range results {
				fields = append(fields, fmt.Sprintf("r%d %s", i, src(t)))
				lhs = append(lhs, fmt.Sprintf("r.r%d", i))
			}
			gps = append(gps, "r *struct{ "+strings.Join(fields, "; ")+" }")
			body = "\t" + strings.Join(lhs, ", ") + " = " + call + "\n"
			cret = "ptr"
		}
		fmt.Fprintf(out, "//go:linkname %s %s\nfunc %s(%s)%s {\n%s}\n\n", sym, sym, sym, strings.Join(gps, ", "), ret, body)
		cside[name] = sym + "|" + strings.Join(cps, ",") + "|" + cret + "|" + strings.Join(cargs, ",")
	}
	return cside, nil
}

var reExportDecl = regexp.MustCompile(`(?m)^extern .* Cgoexp_(\w+) \(.*\) __asm__\("[^"]*"\);\n`)
var reExportFunc = regexp.MustCompile(`(?ms)^(.+?) (\w+) \((.*?)\) \{\n(.*?)\n\}\n`)

// exportsC rewrites _cgo_export.c: each C function of an export calls its
// Go function with the runtime's callback entry and exit around it.
func exportsC(file string, cside map[string]string) error {
	data, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	c := reExportDecl.ReplaceAllString(string(data), "")
	var decls strings.Builder
	decls.WriteString("#include <stdint.h>\nextern int32_t rt_cgo_callback_enter(void);\nextern void rt_cgo_callback_exit(int32_t);\n")
	done := map[string]bool{}
	c = reExportFunc.ReplaceAllStringFunc(c, func(fn string) string {
		m := reExportFunc.FindStringSubmatch(fn)
		cret, name, cparams := strings.TrimSpace(m[1]), m[2], m[3]
		if i := strings.LastIndex(cret, "\n"); i >= 0 {
			cret = strings.TrimSpace(cret[i+1:])
		}
		info, ok := cside[name]
		if !ok {
			return fn
		}
		done[name] = true
		parts := strings.Split(info, "|")
		sym, kinds, rkind, cargs := parts[0], splitNonEmpty(parts[1]), parts[2], splitNonEmpty(parts[3])
		var ptypes []string
		if s := strings.TrimSpace(cparams); s != "" && s != "void" {
			ptypes = splitParams(s)
		}
		if len(ptypes) != len(kinds) {
			return fn
		}
		var dps []string
		for i, k := range kinds {
			ctype := strings.TrimSpace(strings.TrimSuffix(ptypes[i], fmt.Sprintf("p%d", i)))
			switch k {
			case "ptr":
				dps = append(dps, ctype+" *")
			case "same":
				dps = append(dps, ctype)
			default:
				dps = append(dps, k)
			}
		}
		call := sym + "(" + strings.Join(cargs, ", ")
		dret := "void"
		var stmt string
		switch rkind {
		case "void":
			stmt = call + ");"
		case "ptr":
			dps = append(dps, cret+" *")
			if len(cargs) > 0 {
				call += ", "
			}
			stmt = call + "&r);"
		case "same":
			dret = cret
			stmt = "r = " + call + ");"
		default:
			dret = rkind
			stmt = "r = (" + cret + ")" + call + ");"
		}
		if len(dps) == 0 {
			dps = []string{"void"}
		}
		fmt.Fprintf(&decls, "extern %s %s(%s);\n", dret, sym, strings.Join(dps, ", "))
		body := m[4]
		body = strings.Replace(body, "_cgo_tsan_release();", "int32_t _cgo_tok = rt_cgo_callback_enter();", 1)
		body = strings.Replace(body, "_cgo_tsan_acquire();", "rt_cgo_callback_exit(_cgo_tok);", 1)
		body = reExportCall.ReplaceAllString(body, "\t"+stmt)
		return m[1] + " " + name + " (" + cparams + ") {\n" + body + "\n}\n"
	})
	for name := range cside {
		if !done[name] {
			return fmt.Errorf("_cgo_export.c: no C function for the export %s", name)
		}
	}
	// The declarations go after the export header (which has the types).
	inc := "#include \"_cgo_export.h\"\n"
	i := strings.Index(c, inc)
	if i < 0 {
		return fmt.Errorf("_cgo_export.c: no include of _cgo_export.h")
	}
	i += len(inc)
	c = c[:i] + decls.String() + c[i:]
	return os.WriteFile(file, []byte(c), 0o644)
}

var reExportCall = regexp.MustCompile(`(?m)^\t(r = )?Cgoexp_\w+\(.*\);$`)

func splitNonEmpty(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(s, ",")
}

var reCfunc = regexp.MustCompile(`^_(Cfunc|C2func)_(\w+)$`)

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func hashOf(externs map[string]*ast.FuncDecl) string {
	for e := range externs {
		if m := reWrapper.FindStringSubmatch(e); m != nil {
			return m[1]
		}
	}
	return "0"
}

// cvar matches cgo's var Cvar_x *T.
func cvar(d *ast.GenDecl) *ast.ValueSpec {
	if len(d.Specs) != 1 {
		return nil
	}
	v := d.Specs[0].(*ast.ValueSpec)
	if len(v.Names) == 1 && strings.HasPrefix(v.Names[0].Name, "Cvar_") && len(v.Values) == 0 {
		if _, ok := v.Type.(*ast.StarExpr); ok {
			return v
		}
	}
	return nil
}

// cgo2For is the .cgo2.c file of the Go file that uses name.
func cgo2For(dir string, bp *build.Package, name string) string {
	for _, f := range bp.CgoFiles {
		base := strings.TrimSuffix(f, ".go")
		data, _ := os.ReadFile(filepath.Join(dir, base+".cgo1.go"))
		if bytes.Contains(data, []byte(name)) {
			return filepath.Join(dir, base+".cgo2.c")
		}
	}
	return filepath.Join(dir, strings.TrimSuffix(bp.CgoFiles[0], ".go")+".cgo2.c")
}

func sigText(src func(ast.Node) string, t *ast.FuncType) string {
	s := src(t)
	return strings.TrimPrefix(s, "func")
}

// aggregate reports whether a Go type of the cgo output is passed in
// memory or registers differently by LLVM and the C ABI.
func aggregate(t ast.Expr, types map[string]ast.Expr) bool {
	for range 50 {
		switch x := t.(type) {
		case *ast.Ident:
			switch x.Name {
			case "complex64", "complex128":
				return true
			}
			u, ok := types[x.Name]
			if !ok {
				return false
			}
			t = u
		case *ast.ParenExpr:
			t = x.X
		case *ast.StructType, *ast.ArrayType:
			return true
		default:
			return false
		}
	}
	return false
}

// basic follows t to a predeclared type name, or "".
func basic(t ast.Expr, types map[string]ast.Expr) string {
	for range 50 {
		switch x := t.(type) {
		case *ast.Ident:
			u, ok := types[x.Name]
			if !ok {
				return x.Name
			}
			t = u
		case *ast.ParenExpr:
			t = x.X
		default:
			return ""
		}
	}
	return ""
}

// widen is the 32-bit type a small integer argument is passed as, or "".
func widen(t ast.Expr, types map[string]ast.Expr) string {
	switch basic(t, types) {
	case "int8", "int16":
		return "int32"
	case "uint8", "uint16", "byte", "bool":
		return "uint32"
	}
	return ""
}

// pointerish reports whether t is a pointer type.
func pointerish(t ast.Expr, types map[string]ast.Expr) bool {
	for range 50 {
		switch x := t.(type) {
		case *ast.StarExpr:
			return true
		case *ast.SelectorExpr:
			return x.Sel.Name == "Pointer"
		case *ast.Ident:
			u, ok := types[x.Name]
			if !ok {
				return false
			}
			t = u
		case *ast.ParenExpr:
			t = x.X
		default:
			return false
		}
	}
	return false
}

func isBool(t ast.Expr, types map[string]ast.Expr) bool { return basic(t, types) == "bool" }

func isVoid(t ast.Expr) bool {
	id, ok := t.(*ast.Ident)
	return ok && id.Name == "_Ctype_void"
}

// callC writes the _Cfunc_ function d that calls the C wrapper w, its
// extern declaration and, when needed, a C adapter.
func callC(w, cname, kind string, ext, d *ast.FuncDecl, proto cProto, types map[string]ast.Expr,
	src func(ast.Node) string) (goText, cText string, err error) {
	var params []*ast.Field
	for _, f := range ext.Type.Params.List {
		if len(f.Names) == 0 {
			params = append(params, &ast.Field{Names: []*ast.Ident{ast.NewIdent(fmt.Sprintf("p%d", len(params)))}, Type: f.Type})
			continue
		}
		for _, n := range f.Names {
			params = append(params, &ast.Field{Names: []*ast.Ident{n}, Type: f.Type})
		}
	}
	var ret ast.Expr
	if ext.Type.Results != nil && len(ext.Type.Results.List) == 1 {
		ret = ext.Type.Results.List[0].Type
	}
	void := ret == nil || isVoid(ret)
	needAdapter := !void && aggregate(ret, types)
	for _, p := range params {
		if aggregate(p.Type, types) {
			needAdapter = true
		}
	}
	callee := w
	var extParams, args []string
	for i, p := range params {
		name := fmt.Sprintf("p%d", i)
		if needAdapter && aggregate(p.Type, types) {
			extParams = append(extParams, name+" *"+src(p.Type))
			args = append(args, "&"+name)
		} else if w := widen(p.Type, types); w != "" {
			// C expects small integers extended to 32 bits by the caller;
			// do it in Go rather than rely on signext and zeroext.
			extParams = append(extParams, name+" "+w)
			if w == "uint32" && isBool(p.Type, types) {
				args = append(args, "_cgo_b2u("+name+")")
			} else {
				args = append(args, w+"("+name+")")
			}
		} else {
			extParams = append(extParams, name+" "+src(p.Type))
			args = append(args, name)
		}
	}
	extRet := ""
	if needAdapter {
		callee = w + "_m"
		if !void && aggregate(ret, types) {
			extParams = append(extParams, "r *"+src(ret))
			args = append(args, "&r")
		} else if !void {
			extRet = " " + src(ret)
		}
		if proto.file == "" {
			return "", "", fmt.Errorf("no C prototype for %s", w)
		}
		if len(proto.params) != len(params) {
			return "", "", fmt.Errorf("C prototype of %s has %d parameters, Go %d", w, len(proto.params), len(params))
		}
		var cps, cargs []string
		for i, p := range proto.params {
			name := fmt.Sprintf("p%d", i)
			ctype := strings.TrimSpace(strings.TrimSuffix(p, name))
			if aggregate(params[i].Type, types) {
				cps = append(cps, ctype+" *"+name)
				cargs = append(cargs, "*"+name)
			} else {
				cps = append(cps, p)
				cargs = append(cargs, name)
			}
		}
		call := fmt.Sprintf("%s(%s)", w, strings.Join(cargs, ", "))
		switch {
		case void:
			cText = fmt.Sprintf("\nvoid %s(%s) { %s; }\n", callee, strings.Join(cps, ", "), call)
		case aggregate(ret, types):
			cps = append(cps, proto.ret+" *r")
			cText = fmt.Sprintf("\nvoid %s(%s) { *r = %s; }\n", callee, strings.Join(cps, ", "), call)
		default:
			cText = fmt.Sprintf("\n%s %s(%s) { return %s; }\n", proto.ret, callee, strings.Join(cps, ", "), call)
		}
	} else if !void {
		extRet = " " + src(ret)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "//go:linkname %s %s\nfunc %s(%s)%s\n\n", callee, callee, callee, strings.Join(extParams, ", "), extRet)
	call := fmt.Sprintf("%s(%s)", callee, strings.Join(args, ", "))
	rt := "_Ctype_void"
	if ret != nil {
		rt = src(ret)
	}
	fmt.Fprintf(&b, "func %s%s {\n", d.Name.Name, sigText(src, d.Type))
	b.WriteString("\tvar r " + rt + "\n")
	switch {
	case needAdapter && !void && aggregate(ret, types), void:
		b.WriteString("\t" + call + "\n")
	default:
		b.WriteString("\tr = " + call + "\n")
	}
	for i, p := range params {
		if pointerish(p.Type, types) {
			fmt.Fprintf(&b, "\t_cgo_keep(unsafe.Pointer(p%d))\n", i)
		}
	}
	if kind == "C2func" {
		b.WriteString("\tif e := _cgo_rt_errno(); e != 0 {\n\t\treturn r, syscall.Errno(e)\n\t}\n\treturn r, nil\n}\n\n")
	} else {
		b.WriteString("\treturn r\n}\n\n")
	}
	return b.String(), cText, nil
}

var reProto = regexp.MustCompile(`(?m)^(.+)\n(_cgo_[0-9a-f]+_C2?func_\w+)\((.*)\)\n\{`)

// readProtos reads the C wrapper prototypes of the .cgo2.c files.
func readProtos(dir string) (map[string]cProto, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.cgo2.c"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	protos := map[string]cProto{}
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		for _, m := range reProto.FindAllStringSubmatch(string(data), -1) {
			p := cProto{file: file, ret: strings.TrimSpace(m[1])}
			if s := strings.TrimSpace(m[3]); s != "" && s != "void" {
				p.params = splitParams(s)
			}
			protos[m[2]] = p
		}
	}
	return protos, nil
}

// splitParams splits "int p0, struct x p1" at the commas between
// parameters (a type may contain commas only inside parentheses).
func splitParams(s string) []string {
	var out []string
	depth, start := 0, 0
	for i, c := range s {
		switch c {
		case '(':
			depth++
		case ')':
			depth--
		case ',':
			if depth == 0 {
				out = append(out, strings.TrimSpace(s[start:i]))
				start = i + 1
			}
		}
	}
	return append(out, strings.TrimSpace(s[start:]))
}

var reBody = regexp.MustCompile(`(?ms)^(_cgo_[0-9a-f]+_(C2?func)_(\w+))\(.*?\n\}\n`)

// bracket replaces cgo's thread sanitizer hooks in each wrapper with the
// runtime's entry and exit.
func bracket(c string, mk marks) string {
	return reBody.ReplaceAllStringFunc(c, func(body string) string {
		m := reBody.FindStringSubmatch(body)
		kind, name := m[2], m[3]
		enter, exit := "rt_cgo_enter();", "rt_cgo_exit();"
		switch {
		case kind == "C2func":
			enter, exit = "rt_cgo_enter(); errno = 0;", "rt_cgo_exit_errno(errno);"
		case mk.fast(name):
			enter, exit = "rt_cgo_enter_fast();", "rt_cgo_exit_fast();"
		}
		body = strings.Replace(body, "_cgo_tsan_acquire();", enter, 1)
		return strings.Replace(body, "_cgo_tsan_release();", exit, 1)
	})
}
