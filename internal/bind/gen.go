// Generate writes the Go bindings of h. The report lists what was not
// bound and what bind assumed, so that bind.toml can settle it.
func Generate(cfg *Config, h *Header, include string) (src []byte, report []string, err error) {
	g := &gen{cfg: cfg, h: h, handles: map[string]*handle{}, aliases: map[string]string{}, enums: map[string]string{},
		macroVal: map[string]string{}, used: map[string]bool{}, usedType: map[string]bool{}}
	g.setup()
	g.emitMacros()
	g.emitEnums()
	// Functions first, into their own buffer: only the types they use are
	// emitted.
	head := g.body.String()
	g.body.Reset()
	g.emitFuncs()
	funcs := g.body.String()
	g.body.Reset()
	g.body.WriteString(head)
	g.emitTypes()
	g.body.WriteString(funcs)
	g.emitError()

	var out strings.Builder
	pkg := cfg.Package
	if pkg == "" {
		pkg = goPkgName(include)
	}
	fmt.Fprintf(&out, "// Code generated by marmot bind from %s; DO NOT EDIT.\n\n", include)
	fmt.Fprintf(&out, "// Package %s is a binding of the C library declared in %s.\npackage %s\n\n", pkg, include, pkg)
	out.WriteString("/*\n")
	if cfg.PkgConfig != "" {
		fmt.Fprintf(&out, "#cgo pkg-config: %s\n", cfg.PkgConfig)
	}
	if len(cfg.CFlags) > 0 {
		fmt.Fprintf(&out, "#cgo CFLAGS: %s\n", strings.Join(cfg.CFlags, " "))
	}
	if len(cfg.LDFlags) > 0 {
		fmt.Fprintf(&out, "#cgo LDFLAGS: %s\n", strings.Join(cfg.LDFlags, " "))
	}
	fmt.Fprintf(&out, "#include <stdlib.h>\n#include <%s>\n*/\nimport \"C\"\n\n", include)
	var imps []string
	for _, i := range []string{"fmt", "unsafe"} {
		if g.used[i] {
			imps = append(imps, strconv.Quote(i))
		}
	}
	if len(imps) > 0 {
		fmt.Fprintf(&out, "import (\n\t%s\n)\n\n", strings.Join(imps, "\n\t"))
	}
	out.WriteString(g.body.String())
	src, err = format.Source([]byte(out.String()))
	if err != nil {
		return []byte(out.String()), g.report, fmt.Errorf("generated Go does not parse: %v", err)
	}
	return src, g.report, nil
}

type gen struct {
	cfg      *Config
	h        *Header
	body     strings.Builder
	report   []string
	handles  map[string]*handle // C record name -> opaque handle
	aliases  map[string]string  // C record name -> Go alias of the C struct
	enums    map[string]string  // C enum name -> Go type
	macroVal map[string]string  // macro name -> Go const name
	used     map[string]bool    // imports
	names    map[string]bool    // top-level Go names taken
	methods  map[string]map[string]bool
	// hasStatus: some function returns an error from a status result.
	hasStatus bool
	funcNames map[string]bool
	usedType  map[string]bool // Go types the bound functions use
}

type handle struct {
	c      string // the C spelling, as in C.sqlite3 or C.struct_foo
	goName string
	doc    string
	close  string // C function freeing it
	ptr    bool   // c is a pointer typedef (gzFile), not the struct
}

func (g *gen) note(format string, args ...any) {
	g.report = append(g.report, fmt.Sprintf(format, args...))
}

// cName is the C name of a record as cgo spells it.
func cName(r *Record) string {
	if r.Typedef != "" {
		return r.Typedef
	}
	return r.Tag + "_" + r.Name
}

func (g *gen) setup() {
	g.names = map[string]bool{"Error": true}
	g.methods = map[string]map[string]bool{}
	// Records used through pointers become handles (opaque) or aliases of
	// the C struct (complete).
	seen := map[*Record]bool{}
	var recs []*Record
	for _, k := range sortedKeys(g.h.Records) {
		r := g.h.Records[k]
		if !seen[r] {
			seen[r] = true
			recs = append(recs, r)
		}
	}
	for _, r := range recs {
		c := cName(r)
		name := g.typeName(c, r.Name)
		if r.Complete {
			g.aliases[r.Name] = name
			if r.Typedef != "" {
				g.aliases[r.Typedef] = name
			}
		} else {
			hd := &handle{c: c, goName: name, doc: r.Doc}
			g.handles[r.Name] = hd
			if r.Typedef != "" {
				g.handles[r.Typedef] = hd
			}
		}
		g.names[name] = true
	}
	// typedef struct foo *foo_t: the handle wraps the pointer typedef.
	for _, td := range g.h.PtrHandles {
		name := g.typeName(td, td)
		if g.names[name] {
			continue
		}
		g.handles[td] = &handle{c: td, goName: name, doc: g.h.HandleDoc[td], ptr: true}
		g.names[name] = true
	}
	// Names of top-level functions win over constants.
	g.funcNames = map[string]bool{}
	for _, fn := range g.h.Funcs {
		if g.cfg.included(fn.Name) {
			g.funcNames[goName(fn.Name, g.cfg.Prefixes)] = true
		}
	}
	for c, fn := range g.cfg.Close {
		if hd := g.handles[c]; hd != nil {
			hd.close = fn
		}
	}
	for _, e := range g.h.Enums {
		if e.Name != "" {
			g.enums[e.Name] = g.typeName(e.Name, e.Name)
		}
	}
}

// typeName is the Go name of a C type.
func (g *gen) typeName(c, tag string) string {
	if n, ok := g.cfg.Types[c]; ok {
		return n
	}
	if n, ok := g.cfg.Types[tag]; ok {
		return n
	}
	n := goName(c, g.cfg.Prefixes)
	if n == "" || n == "X" {
		n = goName(c, nil)
	}
	return n
}

// goName turns a C name into an exported Go name: prefixes stripped,
// snake_case to CamelCase, known initialisms in capitals.
func goName(c string, prefixes []string) string {
	best := ""
	for _, p := range prefixes {
		if strings.HasPrefix(c, p) && len(p) > len(best) && len(c) > len(p) {
			best = p
		}
	}
	c = strings.TrimPrefix(c, best)
	c = strings.TrimPrefix(strings.TrimPrefix(c, "struct_"), "union_")
	var b strings.Builder
	for _, part := range strings.Split(c, "_") {
		if part == "" {
			continue
		}
		up := strings.ToUpper(part)
		switch {
		case initialisms[up]:
			b.WriteString(up)
		case part == up:
			b.WriteString(up[:1] + strings.ToLower(up[1:]))
		default:
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	n := b.String()
	if n != "" && !unicode.IsLetter(rune(n[0])) {
		n = "X" + n
	}
	return n
}

var initialisms = map[string]bool{"OK": true, "ID": true, "IO": true, "UTF8": true, "UTF16": true, "API": true, "DB": true,
	"SQL": true, "URL": true, "URI": true, "HTTP": true, "JSON": true, "CPU": true, "GPU": true, "RGB": true, "RGBA": true,
	"UTF": true, "CRC": true, "ADLER": false}

func goPkgName(include string) string {
	b := include
	if i := strings.LastIndexAny(b, "/\\"); i >= 0 {
		b = b[i+1:]
	}
	b = strings.TrimSuffix(b, ".h")
	var out strings.Builder
	for _, r := range strings.ToLower(b) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			out.WriteRune(r)
		}
	}
	if out.Len() == 0 || unicode.IsDigit(rune(out.String()[0])) {
		return "c" + out.String()
	}
	return out.String()
}

func sortedKeys[V any](m map[string]V) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// doc writes a Go doc comment: a first line naming the Go and C names, then
// the C documentation (at most 12 lines).
func (g *gen) doc(goName, first, cdoc string) {
	fmt.Fprintf(&g.body, "// %s %s\n", goName, first)
	if cdoc == "" {
		return
	}
	lines := strings.Split(cdoc, "\n")
	more := false
	if len(lines) > 12 {
		lines, more = lines[:12], true
	}
	g.body.WriteString("//\n")
	for _, l := range lines {
		if l == "" {
			g.body.WriteString("//\n")
		} else {
			g.body.WriteString("// " + l + "\n")
		}
	}
	if more {
		g.body.WriteString("// ...\n")
	}
}

// ---- constants ----

var reMacroTok = regexp.MustCompile(`0[xX][0-9a-fA-F]+[uUlL]*|[0-9]+\.[0-9]*([eE][-+]?[0-9]+)?[fFlL]?|[0-9]+[uUlL]*|[A-Za-z_]\w*|"(?:[^"\\]|\\.)*"|<<|>>|[-+*/%|&^~()]|\s+`)

// goExpr translates a macro value to a Go constant expression, or "".
func (g *gen) goExpr(e string) string {
	toks := reMacroTok.FindAllString(e, -1)
	if strings.Join(toks, "") != e {
		return "" // something not understood (casts, braces, calls)
	}
	var b strings.Builder
	for _, t := range toks {
		switch {
		case strings.TrimSpace(t) == "":
			b.WriteString(" ")
		case t[0] == '"':
			b.WriteString(t)
		case t == "~":
			b.WriteString("^")
		case unicode.IsDigit(rune(t[0])):
			b.WriteString(strings.TrimRight(t, "uUlLfF"))
		case unicode.IsLetter(rune(t[0])) || t[0] == '_':
			n, ok := g.macroVal[t]
			if !ok {
				return ""
			}
			b.WriteString(n)
		default:
			b.WriteString(t)
		}
	}
	return strings.TrimSpace(b.String())
}

func (g *gen) emitMacros() {
	var lines []string
	for _, m := range g.h.Macros {
		if !g.cfg.included(m.Name) {
			continue
		}
		v := g.goExpr(m.Expr)
		name := goName(m.Name, g.cfg.Prefixes)
		if g.funcNames[name] || g.names[name] {
			name = m.Name // a function has the name: the constant keeps its C name
		}
		if v == "" || name == "" || g.names[name] {
			continue
		}
		g.names[name] = true
		g.macroVal[m.Name] = name
		lines = append(lines, fmt.Sprintf("\t%s = %s // %s", name, v, m.Name))
	}
	if len(lines) > 0 {
		g.body.WriteString("// Constants from #define.\nconst (\n" + strings.Join(lines, "\n") + "\n)\n\n")
	}
}

func (g *gen) emitEnums() {
	for _, e := range g.h.Enums {
		if len(e.Consts) == 0 || e.Name != "" && !g.cfg.included(e.Name) {
			continue
		}
		typ := g.enums[e.Name]
		if typ != "" {
			g.doc(typ, "is the C enum "+e.Name+".", e.Doc)
			fmt.Fprintf(&g.body, "type %s int\n\n", typ)
		}
		var names []string
		g.body.WriteString("const (\n")
		for _, c := range e.Consts {
			n := goName(c.Name, g.cfg.Prefixes)
			if n == "" || g.names[n] {
				n = goName(c.Name, nil)
			}
			if g.names[n] {
				g.note("enum constant %s: the Go name %s is taken; left out", c.Name, n)
				continue
			}
			g.names[n] = true
			g.macroVal[c.Name] = n
			if typ != "" {
				fmt.Fprintf(&g.body, "\t%s %s = %d // %s\n", n, typ, c.Value, c.Name)
			} else {
				fmt.Fprintf(&g.body, "\t%s = %d // %s\n", n, c.Value, c.Name)
			}
			names = append(names, n)
		}
		g.body.WriteString(")\n\n")
		if typ != "" {
			fmt.Fprintf(&g.body, "// String returns the C name of the constant.\nfunc (v %s) String() string {\n\tswitch v {\n", typ)
			done := map[int64]bool{}
			for i, c := range e.Consts {
				if i < len(names) && !done[c.Value] {
					done[c.Value] = true
					fmt.Fprintf(&g.body, "\tcase %s:\n\t\treturn %q\n", names[i], c.Name)
				}
			}
			g.used["fmt"] = true
			fmt.Fprintf(&g.body, "\t}\n\treturn fmt.Sprintf(\"%s(%%d)\", int(v))\n}\n\n", typ)
		}
	}
}

func (g *gen) emitTypes() {
	done := map[string]bool{}
	for _, k := range sortedKeys(g.handles) {
		hd := g.handles[k]
		if done[hd.goName] || !g.usedType[hd.goName] {
			continue
		}
		done[hd.goName] = true
		g.doc(hd.goName, "is a handle to the C type "+hd.c+".", hd.doc)
		ct := "*C." + hd.c
		if hd.ptr {
			ct = "C." + hd.c
		}
		fmt.Fprintf(&g.body, "type %s struct {\n\tp %s\n}\n\n", hd.goName, ct)
		fmt.Fprintf(&g.body, "func (h *%s) c() %s {\n\tif h == nil {\n\t\treturn nil\n\t}\n\treturn h.p\n}\n\n", hd.goName, ct)
		fmt.Fprintf(&g.body, "func wrap%s(p %s) *%s {\n\tif p == nil {\n\t\treturn nil\n\t}\n\treturn &%s{p}\n}\n\n", hd.goName, ct, hd.goName, hd.goName)
		if hd.close == "" {
			g.note("handle %s (%s): no free function in [close]; it has no Close method", hd.goName, hd.c)
		}
	}
	for _, k := range sortedKeys(g.aliases) {
		r := g.h.Records[k]
		name := g.aliases[k]
		if done[name] || r == nil || !g.usedType[name] {
			continue
		}
		done[name] = true
		g.doc(name, "is the C "+r.Tag+" "+cName(r)+" (fields keep their C types).", r.Doc)
		fmt.Fprintf(&g.body, "type %s = C.%s\n\n", name, cName(r))
	}
}
