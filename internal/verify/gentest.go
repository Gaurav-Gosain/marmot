package verify

import (
	"fmt"
	"slices"
	"strings"
)

// GenTest is one generated regression test: the call that panics.
type GenTest struct {
	Name    string // TestMarmotVerify_Fn_N
	Comment string // where and why it panics
	Call    string // Go source of the call
}

// TestName is the test name of the n-th test (from 1) for function fn
// (its full name; the receiver type joins the name for methods).
func TestName(fn string, n int) string {
	short := fn
	if i := strings.LastIndex(short, "/"); i >= 0 {
		short = short[i+1:]
	}
	if i := strings.Index(short, "."); i >= 0 {
		short = short[i+1:]
	}
	r := strings.NewReplacer("(", "", ")", "", "*", "", ".", "_", "$", "_")
	return fmt.Sprintf("TestMarmotVerify_%s_%d", r.Replace(short), n)
}

// TestFile is the source of a generated test file for package pkg:
// plain Go that fails under gc until the panics are fixed, then keeps
// them fixed.
func TestFile(pkg string, tests []GenTest) string {
	slices.SortFunc(tests, func(a, b GenTest) int { return strings.Compare(a.Name, b.Name) })
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by marmot verify; DO NOT EDIT.\n\npackage %s\n\nimport \"testing\"\n", pkg)
	for _, t := range tests {
		fmt.Fprintf(&b, "\nfunc %s(t *testing.T) {\n", t.Name)
		for _, l := range strings.Split(t.Comment, "\n") {
			fmt.Fprintf(&b, "\t// %s\n", l)
		}
		// Recover so each test fails on its own instead of ending the
		// test binary.
		fmt.Fprintf(&b, "\tdefer func() {\n\t\tif r := recover(); r != nil {\n\t\t\tt.Fatalf(\"%%s panics: %%v\", %q, r)\n\t\t}\n\t}()\n", t.Call)
		fmt.Fprintf(&b, "\t%s\n}\n", t.Call)
	}
	return b.String()
}
