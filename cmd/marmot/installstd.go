package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/Gaurav-Gosain/marmot/internal/driver"
)

// install-std: compiles the standard library once, so a program's first dev
// build links std at -O 2 instead of compiling it at tier 0. A program that
// imports every std package is built in dev mode with MARMOT_TIER1=sync: the
// build caches the std modules, and the tier 1 runner, which the build waits
// for, caches their -O2 objects. Later dev builds of any program find them by
// the same keys (a module's key is its package's sources, its dependencies'
// and the configuration, not the program). Measured on linux/amd64: 170
// packages in 32 s and 193 MB of cache; tuios's first dev build then takes
// 233 of its 506 modules from it (21.3 s and 137 MB instead of 24.2 s and
// 157 MB).

// stdSkip are the std packages a program cannot import here: internal and
// vendored packages, commands, and packages of other platforms or tools.
var stdSkip = regexp.MustCompile(`(^|/)(internal|vendor)(/|$)|^cmd/|^syscall/js$|^plugin$|^runtime/(cgo|race|msan|asan)$|^testing/|^log/syslog$`)

func cmdInstallStd(args []string) int {
	target := ""
	for i := 0; i < len(args); i++ {
		switch a := strings.TrimLeft(args[i], "-"); {
		case a == "target" && i+1 < len(args):
			target = args[i+1]
			i++
		case strings.HasPrefix(a, "target="):
			target = strings.TrimPrefix(a, "target=")
		default:
			return usageError("install-std", fmt.Errorf("unknown argument %q (want -target GOOS/GOARCH)", args[i]))
		}
	}
	root, err := driver.FindRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "marmot:", err)
		return 1
	}
	self, err := os.Executable()
	if err != nil {
		fmt.Fprintln(os.Stderr, "marmot:", err)
		return 1
	}
	// The program lives in the cache: its MLIR and objects are what this
	// command is for, and its directory is rewritten on every run.
	dir := filepath.Join(root, "build", "cache", "install-std")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "marmot:", err)
		return 1
	}
	list := exec.Command("go", "list", "std")
	list.Dir = dir
	if target != "" {
		if goos, goarch, ok := strings.Cut(target, "/"); ok {
			list.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch)
		}
	}
	out, err := list.Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "marmot: go list std:", err)
		return 1
	}
	var src strings.Builder
	src.WriteString("// Generated by marmot install-std: every std package, for its cached objects.\npackage main\n\nimport (\n")
	n := 0
	for _, p := range strings.Fields(string(out)) {
		if stdSkip.MatchString(p) {
			continue
		}
		fmt.Fprintf(&src, "\t_ %q\n", p)
		n++
	}
	src.WriteString(")\n\nfunc main() {}\n")
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module marmotstd\n\ngo 1.24\n"), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "marmot:", err)
		return 1
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(src.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "marmot:", err)
		return 1
	}
	bargs := []string{"build", "-o", filepath.Join(dir, "allstd")}
	if target != "" {
		bargs = append(bargs, "-target", target)
	}
	bargs = append(bargs, ".")
	build := exec.Command(self, bargs...)
	build.Dir = dir
	build.Env = append(os.Environ(), "MARMOT_TIER1=sync")
	build.Stdout, build.Stderr = os.Stdout, os.Stderr
	start := time.Now()
	fmt.Printf("install-std: compiling %d std packages (dev, tier 1 at -O 2)\n", n)
	if err := build.Run(); err != nil {
		fmt.Fprintln(os.Stderr, "marmot: install-std:", err)
		return 1
	}
	_ = os.Remove(filepath.Join(dir, "allstd")) // only its objects are wanted
	size, files := driver.CacheSize(root)
	fmt.Printf("install-std: done in %.1f s; cache %.1f MB in %d files\n", time.Since(start).Seconds(), float64(size)/(1<<20), files)
	return 0
}
